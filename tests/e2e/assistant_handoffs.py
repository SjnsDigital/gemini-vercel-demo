"""Cross-page shortcuts, including repeated commands after manual changes."""
import json, os, re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base=os.environ.get('KIMSOLAR_TEST_URL','http://127.0.0.1:5173').rstrip('/')+'/'
out=Path(os.environ.get('KIMSOLAR_TEST_OUTPUT','test-results/handoffs'));out.mkdir(parents=True,exist_ok=True)
def command(page,text,button):
    expect(page.locator('.agent-workbench-toggle')).to_be_visible()
    toggle=page.get_by_role('button',name='Mở trợ lý nghiệp vụ',exact=True)
    if toggle.count():toggle.click()
    page.get_by_label('Yêu cầu trợ lý nghiệp vụ',exact=True).fill(text)
    page.get_by_role('button',name='Phân tích yêu cầu',exact=True).click()
    page.get_by_role('region',name='Kết quả trợ lý',exact=True).get_by_role('button',name=button,exact=True).click()

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000},timezone_id='Asia/Ho_Chi_Minh',accept_downloads=True)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base+'#lookup')
    page.get_by_label('Hóa đơn tra nhanh',exact=True).fill('2.2')
    expect(page.get_by_label('Hóa đơn tra nhanh',exact=True).locator('..')).to_contain_text('2.200.000')
    page.get_by_role('button',name='Dùng mức này',exact=True).click()
    expect(page.get_by_label('Hóa đơn trung bình tháng',exact=True).locator('..')).to_contain_text('2.200.000')
    page.get_by_role('button',name='Lưu phương án',exact=True).click()
    dialog=page.get_by_role('dialog',name='Lưu phương án')
    dialog.get_by_label('Tên phương án',exact=True).fill('QA Liền mạch')
    dialog.get_by_role('button',name='Lưu phương án',exact=True).click()
    command(page,'So sánh phương án','Mở bảng so sánh')
    expect(page.locator('.plan-compare-toggle')).to_have_attribute('aria-expanded','true')
    page.locator('.plan-compare-toggle').click()
    expect(page.locator('.plan-compare-toggle')).to_have_attribute('aria-expanded','false')
    command(page,'So sánh phương án','Mở bảng so sánh')
    expect(page.locator('.plan-compare-toggle')).to_have_attribute('aria-expanded','true')
    print('PASS direct shorthand lookup→saved plan and repeated compare command reopens panel',flush=True)
    page.goto(base+'#knowledge');expect(page.get_by_role('heading',name='Đúng thông tin. Đúng thời điểm.',exact=True)).to_be_visible()
    command(page,'Giải thích hoàn vốn','Mở cẩm nang liên quan')
    expect(page.get_by_label('Tìm cẩm nang',exact=True)).to_have_value('hoàn vốn')
    page.get_by_label('Tìm cẩm nang',exact=True).fill('xyz')
    command(page,'Giải thích hoàn vốn','Mở cẩm nang liên quan')
    expect(page.get_by_label('Tìm cẩm nang',exact=True)).to_have_value('hoàn vốn')
    print('PASS repeated knowledge command resets manual query',flush=True)
    page.goto(base+'#catalog');expect(page.get_by_role('heading',name='Mỗi lựa chọn, một tiêu chuẩn.',exact=True)).to_be_visible()
    command(page,'Thiết bị chưa xác minh','Mở danh mục cần kiểm tra')
    expect(page.get_by_label('Lọc thiết bị',exact=True)).to_have_value('unverified')
    command(page,'Tìm pin lưu trữ','Mở danh mục tìm thấy')
    expect(page.get_by_label('Tìm thiết bị',exact=True)).to_have_value('')
    expect(page.locator('.record-product')).to_have_count(2)
    print('PASS catalog agent applies actual verification and category filters',flush=True)
    page.goto(base+'#quotes');expect(page.get_by_role('heading',name='Báo giá & đề xuất',exact=True)).to_be_visible()
    command(page,'Tạo báo giá mới','Mở báo giá mới')
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('dialog').get_by_role('button',name='Đóng báo giá',exact=True).click()
    command(page,'Báo giá nào còn nháp?','Mở báo giá nháp')
    expect(page.locator('.ks-filter-pills').get_by_role('button',name='Bản nháp',exact=True)).to_have_class(re.compile('active'))
    print('PASS quote assistant opens editor and applies draft filter',flush=True)
    page.goto(base+'#settings')
    page.get_by_role('button',name=re.compile('Giá & định mức')).click()
    field=page.locator('#rate-labor');field.fill('2.2')
    expect(field.locator('..')).to_contain_text('2.200.000')
    page.locator('form').get_by_role('button',name=re.compile('Lưu')).click()
    stored=json.loads(page.evaluate('localStorage.getItem("kimsolar.workspace.v2")'))
    assert stored['settings']['installationRates']['labor']==2200000
    with page.expect_download() as event:command(page,'Sao lưu ngay','Tải bản sao lưu')
    path=out/'assistant-backup.json';event.value.save_as(str(path))
    backup=json.loads(path.read_text());assert backup['app']=='kimsolar-workspace' and backup['db']['plans'][0]['name']=='QA Liền mạch'
    print('PASS compact settings rate persists and assistant downloads real complete backup',flush=True)
    assert not errors,errors
    browser.close()
